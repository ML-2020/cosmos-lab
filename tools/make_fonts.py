#!/usr/bin/env python3 -I
"""Subset the two embedded faces and write src/fonts.css (data URIs).
   display : Noto Serif CJK SC Black, only the characters between the display markers of src/ui/text.js (+ EXTRA)
   latin   : Bricolage Grotesque variable (opsz/wdth/wght), ASCII + a few typographic symbols
Run:  python3 -I tools/make_fonts.py
"""
import base64, re, subprocess, sys, tempfile, os, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
scratch = pathlib.Path(os.environ.get('FONT_SRC', '/tmp/claude-0/-home-claude/f5b31a29-7dbc-562c-a792-dce82efc1b06/scratchpad/fontsrc'))
txt = (root / 'src/ui/text.js').read_text(encoding='utf8')
block = re.search(r'/\*display:start\*/(.*?)/\*display:end\*/', txt, re.S).group(1)
EXTRA = '摄影师模式延时星轨取景观测者图层假说参数现在播放暂停'
chars = sorted({c for c in block + EXTRA if ord(c) > 0x2E80 or c in '·—“”‘’，。：；！？、（）《》'})
print('display characters:', len(chars))

def subset(src, out, args):
    subprocess.run(['pyftsubset', str(src), f'--output-file={out}', '--flavor=woff2', '--no-hinting', '--desubroutinize',
                    '--layout-features=kern,liga,calt,ccmp,locl,mark,mkmk', *args], check=True)

tmp = pathlib.Path(tempfile.mkdtemp())
disp = tmp / 'disp.woff2'
subset('/usr/share/fonts/opentype/noto/NotoSerifCJK-Black.ttc', disp, ['--font-number=2', '--text=' + ''.join(chars) + '0123456789'])
lat = tmp / 'lat.woff2'
uni = 'U+0020-007E,U+00B0,U+00B7,U+00D7,U+2032,U+2033,U+2013,U+2014,U+2018,U+2019,U+201C,U+201D,U+00B1,U+2248,U+2260,U+2192,U+2190,U+2191,U+2193,U+2026,U+2212,U+2022'
subset(scratch / 'package/files/bricolage-grotesque-latin-standard-normal.woff2', lat, ['--unicodes=' + uni])
b64 = lambda p: base64.b64encode(p.read_bytes()).decode()
css = f"""/* generated by tools/make_fonts.py - do not edit */
@font-face{{font-family:'Display';src:url(data:font/woff2;base64,{b64(disp)}) format('woff2');font-weight:900;font-style:normal;font-display:block}}
@font-face{{font-family:'Bricolage';src:url(data:font/woff2;base64,{b64(lat)}) format('woff2');font-weight:200 800;font-stretch:75% 100%;font-style:normal;font-display:block}}
"""
(root / 'src/fonts.css').write_text(css, encoding='utf8')
print('display woff2', disp.stat().st_size, 'bytes; latin woff2', lat.stat().st_size, 'bytes')
